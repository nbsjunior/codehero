/**
 * Bundles hero-scan + contracts + engine into a single CJS file shipped inside the VSIX.
 * Requires prior `npm run build` of contracts, engine, and scanner (dist/).
 */
import { mkdirSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { spawnSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(root, "..", "..");
const outfile = join(root, "bundled", "hero-scan.cjs");
const scannerEntry = join(repo, "packages", "scanner", "dist", "index.js");

if (!existsSync(scannerEntry)) {
  console.error("Missing packages/scanner/dist. Run: npm run build:scanner (and contracts/engine first).");
  process.exit(1);
}

mkdirSync(dirname(outfile), { recursive: true });

const require = createRequire(import.meta.url);
let esbuildBin = null;
try {
  esbuildBin = require.resolve("esbuild/bin/esbuild", { paths: [repo] });
} catch {
  /* fall through to npx */
}

const args = [
  scannerEntry,
  "--bundle",
  "--platform=node",
  "--format=cjs",
  "--target=node20",
  `--outfile=${outfile}`,
  "--log-level=info",
];

const result = esbuildBin
  ? spawnSync(process.execPath, [esbuildBin, ...args], { stdio: "inherit" })
  : spawnSync("npx", ["--yes", "esbuild@0.25.0", ...args], { stdio: "inherit", shell: true });

if (result.status !== 0) process.exit(result.status ?? 1);

writeFileSync(join(root, "bundled", "README.md"), "Bundled deterministic hero-scan (CJS). Generated by scripts/bundle-scanner.mjs.\n");
console.log("wrote", outfile);
