/**
 * Bundles hero-scan + contracts + engine into a single CJS file shipped inside the VSIX.
 * Requires prior `npm run build` of contracts, engine, and scanner (dist/).
 */
import { build } from "esbuild";
import { mkdirSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(root, "..", "..");
const outfile = join(root, "bundled", "hero-scan.cjs");

const scannerEntry = join(repo, "packages", "scanner", "dist", "index.js");
if (!existsSync(scannerEntry)) {
  console.error("Missing packages/scanner/dist. Run: npm run build:scanner (and contracts/engine first).");
  process.exit(1);
}

mkdirSync(dirname(outfile), { recursive: true });

await build({
  entryPoints: [scannerEntry],
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  outfile,
  logLevel: "info",
});

writeFileSync(join(root, "bundled", "README.md"), "Bundled deterministic hero-scan (CJS). Generated by scripts/bundle-scanner.mjs.\n");
console.log("wrote", outfile);
